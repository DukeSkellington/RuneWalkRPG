#!/usr/bin/env python3
"""Author the eight-screen field, Bracken, and Glassmere, and prepack attributes.
Layouts are deterministic compositions, not procedural random scatter."""
import json
import pathlib
import sys
sys.path.insert(0,str(pathlib.Path(__file__).resolve().parents[1]/'assets'))
from terrain import PALETTES, SOLID


def base(width, floor=0):
    m=[[floor]*width for _ in range(15)]
    for x in range(width): m[0][x]=m[14][x]=4
    for y in range(15): m[y][0]=m[y][-1]=4
    return m


def rect(m,x,y,w,h,t):
    for j in range(y,y+h):
        for i in range(x,x+w): m[j][i]=t


def field():
    m=base(128)
    # Quiet flowering western meadow, dense northern forest, eastern highlands.
    for y in range(1,14):
        for x in range(1,127):
            m[y][x]=(2 if (x*7+y*11)%31==0 else 1 if (x+y*3)%13==0 else 0)
    for x,y,w,h in ((2,2,5,3),(20,1,9,4),(25,10,8,4),(48,1,9,4),
                     (52,11,10,3),(69,1,8,4),(73,10,9,4),(115,1,12,4)):
        rect(m,x,y,w,h,3 if x<70 else 4)
        m[y][x]=0; m[y+h-1][x+w-1]=1
        if x<70: m[y+1][x+w-1]=4
    # Pools in the western valley; two vertical rivers with walkable bridges.
    rect(m,15,10,8,3,7); rect(m,16,9,6,1,7)
    for x,w in ((40,4),(84,3)):
        rect(m,x,1,w,13,7)
        for y in range(1,14):
            for i in range(x,x+w): m[y][i]=7
    # Unbroken road gives the player an intentional spine through the landscape.
    for x in range(1,127): m[7][x]=10 if x<70 else 11
    for x,w in ((40,4),(84,3)): rect(m,x,7,w,1,12)
    # Bracken entrance at column 12: roofs, walls, then a marked passage.
    rect(m,10,4,5,1,8); m[4][10]=13; m[4][14]=9; rect(m,10,5,5,1,14)
    m[6][12]=15; m[7][12]=21
    # Rune stones establish the route, becoming denser near the ruin.
    for x,y in ((31,5),(57,9),(74,5),(91,9),(110,5)):
        m[y][x]=17
        m[y+1][x]=11
    # Eastern skyline and ruin approach.
    for x in range(90,126):
        if x%5!=0: m[1][x]=m[2][x]=6
    for x,y in ((66,3),(67,3),(95,11),(96,11),(119,11),(120,11)):
        m[y][x]=5
    rect(m,100,4,5,1,16); m[5][100]=m[5][104]=20
    m[6][102]=17; m[7][102]=21
    # Dead kingdom at the far edge; a final lake and wind-worn causeway.
    rect(m,113,10,11,3,7)
    for x in range(1,127):
        if m[8][x] in (0,1,2) and x%5==0: m[8][x]=23
    return m


def town():
    m=base(32)
    for x in range(1,31): m[7][x]=11
    for x in range(8,23): m[8][x]=11
    for x in (5,17,25):
        rect(m,x,2,4,1,8); m[2][x]=13; m[2][x+3]=9
        rect(m,x,3,4,2,14); m[4][x+1]=15
    rect(m,20,10,7,3,7)
    m[7][1]=21
    m[10][6]=m[11][6]=3
    m[10][7]=m[11][7]=3
    m[9][14]=m[9][15]=2
    m[6][11]=11  # keeper stands above the plaza
    m[6][8]=18
    return m


def ruin():
    m=base(32,19)
    for x in range(32): m[0][x]=m[14][x]=16
    for y in range(15): m[y][0]=m[y][-1]=16
    for x in (4,8,14,19,25,28):
        m[3][x]=m[10][x]=20
    for x in range(2,30):
        if x not in (10,11,22,23): m[2][x]=16
    m[7][1]=21
    m[5][7]=22
    m[6][22]=17
    m[7][22]=11
    for x in range(12,28): m[12][x]=23
    return m


def main():
    scenes=[field(),town(),ruin()]
    out=['/* Generated by tools/generate_world.py; edit the authored layouts there. */']
    for i,m in enumerate(scenes):
        width=len(m[0]); cells=[]; attrs=[]
        for x in range(width): cells.extend([m[y][x] for y in range(15)]+[0])
        for x in range(0,width,2):
            for y in range(0,16,2):
                value=0
                for dy in range(2):
                    for dx in range(2):
                        p=PALETTES[m[y+dy][x+dx]] if y+dy<15 else 0
                        value|=p<<((dy*2+dx)*2)
                attrs.append(value)
        for name,values in ((f'map_{i}',cells),(f'attributes_{i}',attrs)):
            out.append(f'static const u8 {name}[{len(values)}] = {{')
            out.extend('    '+','.join(map(str,values[n:n+32]))+',' for n in range(0,len(values),32))
            out.append('};')
    out.append('static const u8 solid_table[24] = {'+','.join('1' if i in SOLID else '0' for i in range(24))+'};')
    pathlib.Path(sys.argv[1]).write_text('\n'.join(out)+'\n')
    pathlib.Path('build/world.json').write_text(json.dumps(scenes))

if __name__=='__main__': main()
